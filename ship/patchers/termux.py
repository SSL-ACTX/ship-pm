"""Termux environment binary patcher, toolchain manager hooks, and runtime wrapper."""

import os
import platform
import re
import shutil
import socket
import subprocess
from pathlib import Path

from ship.config import HOME, IS_TERMUX, PREFIX
from ship.patchers.base import BinaryPatcher
from ship.ui import status, warn


def get_termux_ssl_cert_file() -> str:
    """Finds the active CA certificate bundle in Termux."""
    candidates = (
        PREFIX / "etc" / "tls" / "cert.pem",
        PREFIX / "etc" / "ssl" / "certs" / "ca-certificates.crt",
        PREFIX / "glibc" / "etc" / "ssl" / "certs" / "ca-certificates.crt",
    )
    for c in candidates:
        if c.is_file():
            return str(c)
    return ""


def is_dns_server_reachable(ip: str, port: int = 53, timeout: float = 0.3) -> bool:
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.settimeout(timeout)
        s.connect((ip, port))
        s.close()
        return True
    except OSError:
        return False


def ensure_termux_resolv_conf() -> None:
    resolv_file = PREFIX / "etc" / "resolv.conf"
    raw_candidates: list[str] = []
    anycast_defaults = ["1.1.1.1", "8.8.8.8", "1.0.0.1", "8.8.4.4"]

    for prop in ("net.dns1", "net.dns2"):
        try:
            val = subprocess.run(
                ["getprop", prop],
                capture_output=True,
                text=True,
                check=False,
            ).stdout.strip()
            if val and not val.startswith("127.") and val not in raw_candidates:
                raw_candidates.append(val)
        except OSError:
            pass

    for ac in anycast_defaults:
        if ac not in raw_candidates:
            raw_candidates.append(ac)

    active_servers: list[str] = []
    for ip in raw_candidates:
        if is_dns_server_reachable(ip):
            active_servers.append(ip)
        if len(active_servers) >= 3:
            break

    if not active_servers:
        active_servers = ["1.1.1.1", "8.8.8.8"]

    content = "# Generated by ship for Termux DNS stability\noptions timeout:1 attempts:2 rotate\n"
    for s in active_servers:
        content += f"nameserver {s}\n"

    try:
        resolv_file.parent.mkdir(parents=True, exist_ok=True)
        resolv_file.write_text(content, encoding="utf-8")
    except OSError:
        pass

    glibc_resolv = PREFIX / "glibc" / "etc" / "resolv.conf"
    if glibc_resolv.parent.is_dir():
        try:
            shutil.copy2(resolv_file, glibc_resolv)
        except OSError:
            pass


def patch_termux_glibc_dir(target_dir: Path) -> None:
    """Recursively patches downloaded toolchain binaries and libraries to run under Termux Glibc."""
    glibc_pfx = Path(os.environ.get("GLIBC_PREFIX", f"{PREFIX}/glibc"))
    arch = platform.machine().lower()

    if arch in ("aarch64", "arm64"):
        loader_name = "ld-linux-aarch64.so.1"
    elif arch in ("x86_64", "amd64"):
        loader_name = "ld-linux-x86-64.so.2"
    elif arch.startswith("arm"):
        loader_name = "ld-linux-armhf.so.3"
    elif re.match(r"^i\d86$", arch):
        loader_name = "ld-linux.so.2"
    elif arch == "riscv64":
        loader_name = "ld-linux-riscv64-lp64d.so.1"
    else:
        return

    loader_path = glibc_pfx / "lib" / loader_name
    patchelf_bin = shutil.which("patchelf")
    if not loader_path.is_file() or not patchelf_bin or not target_dir.is_dir():
        return

    base_rpath = str(glibc_pfx / "lib")

    for root, _, files in os.walk(target_dir):
        for f in files:
            p = Path(root) / f
            if p.is_symlink() or not p.is_file():
                continue
            try:
                with open(p, "rb") as fp:
                    content = fp.read(4096)
                    if not content.startswith(b"\x7fELF"):
                        continue
                    is_dynamic_elf = (
                        b"ld-linux" in content
                        or b"/lib64/ld" in content
                        or b"/lib/ld" in content
                    )

                if is_dynamic_elf:
                    # Provide local library paths for complex runtimes like Julia
                    local_rpath = f"{base_rpath}:{p.parent}:{p.parent.parent / 'lib'}:{p.parent.parent / 'lib' / 'julia'}"
                    subprocess.run(
                        [
                            patchelf_bin,
                            "--set-interpreter",
                            str(loader_path),
                            "--set-rpath",
                            local_rpath,
                            str(p),
                        ],
                        check=False,
                        capture_output=True,
                    )
                elif p.name.endswith(".so") or ".so." in p.name:
                    local_rpath = f"{base_rpath}:{p.parent}:{p.parent.parent / 'lib'}"
                    subprocess.run(
                        [patchelf_bin, "--set-rpath", local_rpath, str(p)],
                        check=False,
                        capture_output=True,
                    )
            except OSError:
                continue


def patch_toolchain_dir(toolchain_name: str) -> None:
    """Helper entry point for runtime wrappers to auto-patch downloaded toolchains."""
    if toolchain_name == "juliaup":
        patch_termux_glibc_dir(HOME / ".julia" / "juliaup")
    elif toolchain_name == "rustup":
        patch_termux_glibc_dir(HOME / ".rustup" / "toolchains")


class TermuxPatcher(BinaryPatcher):
    """
    Termux runtime compatibility patcher:
    - Patches glibc dynamic interpreters and RPATH.
    - Resolves DNS for Musl static binaries via QEMU target sysroot (-L $PREFIX).
    - Auto-patches downloaded toolchains for multiplexers (juliaup, rustup).
    - Injects SSL_CERT_FILE and SSL_CERT_DIR for all Linux tools.
    - Unsets LD_PRELOAD to prevent libtermux-exec.so collisions.
    """

    name = "termux-runtime"

    @staticmethod
    def is_elf(file_path: Path) -> bool:
        try:
            with open(file_path, "rb") as f:
                return f.read(4) == b"\x7fELF"
        except OSError:
            return False

    @staticmethod
    def is_dynamic_glibc_elf(file_path: Path) -> bool:
        try:
            with open(file_path, "rb") as f:
                content = f.read(4096)
                if not content.startswith(b"\x7fELF"):
                    return False
                return (
                    b"ld-linux" in content
                    or b"/lib64/ld" in content
                    or b"/lib/ld" in content
                )
        except OSError:
            return False

    def should_patch(self, binary_path: Path, target_key: str) -> bool:
        return IS_TERMUX and self.is_elf(binary_path)

    def patch(self, binary_path: Path, target_key: str) -> Path:
        glibc_pfx = Path(os.environ.get("GLIBC_PREFIX", f"{PREFIX}/glibc"))
        arch = platform.machine().lower()

        is_glibc = self.is_dynamic_glibc_elf(binary_path)

        if arch in ("aarch64", "arm64"):
            loader_name = "ld-linux-aarch64.so.1"
            qemu_runner = "qemu-aarch64"
        elif arch in ("x86_64", "amd64"):
            loader_name = "ld-linux-x86-64.so.2"
            qemu_runner = "qemu-x86_64"
        elif arch.startswith("arm"):
            loader_name = "ld-linux-armhf.so.3"
            qemu_runner = "qemu-arm"
        elif re.match(r"^i\d86$", arch):
            loader_name = "ld-linux.so.2"
            qemu_runner = "qemu-i386"
        elif arch == "riscv64":
            loader_name = "ld-linux-riscv64-lp64d.so.1"
            qemu_runner = "qemu-riscv64"
        else:
            loader_name = ""
            qemu_runner = ""

        loader_path = glibc_pfx / "lib" / loader_name
        rpath = str(glibc_pfx / "lib")

        # 1. Glibc ELF binary patching
        if is_glibc:
            if loader_path.is_file():
                patchelf_bin = shutil.which("patchelf")
                if patchelf_bin:
                    status("Patching", f"glibc interpreter for {binary_path.name}")
                    try:
                        subprocess.run(
                            [
                                patchelf_bin,
                                "--set-interpreter",
                                str(loader_path),
                                "--set-rpath",
                                rpath,
                                str(binary_path),
                            ],
                            check=True,
                            capture_output=True,
                        )
                    except subprocess.SubprocessError as e:
                        warn(f"patchelf failed for {binary_path.name}: {e}")
                else:
                    warn(
                        f"{binary_path.name} is a glibc ELF. Run 'pkg install patchelf-glibc' for full glibc support."
                    )
            else:
                warn(
                    f"{binary_path.name} was built for glibc. Run 'pkg install glibc' or use 'musl' targets on Termux."
                )

        ensure_termux_resolv_conf()

        # 2. Universal Termux runtime launcher wrapper
        cert_file = get_termux_ssl_cert_file()
        real_binary = binary_path.parent / f"{binary_path.name}-real"

        if not real_binary.exists():
            shutil.move(binary_path, real_binary)

            ssl_exports = ""
            if cert_file:
                cert_dir = str(Path(cert_file).parent)
                ssl_exports = f"""export SSL_CERT_FILE="{cert_file}"
export SSL_CERT_DIR="{cert_dir}"
"""

            bash_bin = (
                f"{PREFIX}/bin/bash" if (PREFIX / "bin/bash").is_file() else "/bin/sh"
            )

            # Auto-patch hooks for toolchain managers
            post_exec_hook = ""
            pre_exec_hook = ""
            if binary_path.name == "juliaup":
                post_exec_hook = """
case "$*" in
    *add*|*update*|*install*|*default*)
        python3 -c "from ship.patchers.termux import patch_toolchain_dir; patch_toolchain_dir('juliaup')" 2>/dev/null || true
        ;;
esac
"""
            elif binary_path.name == "julia":
                pre_exec_hook = """python3 -c "from ship.patchers.termux import patch_toolchain_dir; patch_toolchain_dir('juliaup')" 2>/dev/null || true\n"""

            if is_glibc:
                exec_cmd = f'"{real_binary}" "$@"'
            elif qemu_runner and shutil.which(qemu_runner):
                exec_cmd = f'export QEMU_LD_PREFIX="{PREFIX}"\n{qemu_runner} -L "{PREFIX}" "{real_binary}" "$@"'
            else:
                exec_cmd = f'"{real_binary}" "$@"'

            wrapper_content = f"""#!{bash_bin}
# ship Termux runtime launcher - DNS, SSL & Toolchain Auto-Patching
unset LD_PRELOAD
{ssl_exports}{pre_exec_hook}{exec_cmd}
EXIT_CODE=$?
{post_exec_hook}exit $EXIT_CODE
"""
            binary_path.write_text(wrapper_content, encoding="utf-8")
            binary_path.chmod(0o755)
            real_binary.chmod(0o755)

        return binary_path
